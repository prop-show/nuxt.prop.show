import assert from 'node:assert/strict'
import { Buffer } from 'node:buffer'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = new URL('../', import.meta.url)
const names = new Set()

function scan(source) {
    for (const match of source.matchAll(/\b(?:i-)?(tabler|lucide)[-:]([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
        names.add(`${match[1]}:${match[2]}`)
    }
}

async function scanDirectory(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = new URL(entry.name, directory)
        if (entry.isDirectory())
            await scanDirectory(new URL(`${entry.name}/`, directory))
        else if (/\.(?:vue|[cm]?[jt]sx?)$/.test(entry.name))
            scan(await readFile(path, 'utf8'))
    }
}

for (const directory of ['src/components/', 'src/pages/'])
    await scanDirectory(new URL(directory, root))
scan(await readFile(new URL('src/site-config.ts', root), 'utf8'))

// Read the installed defaults without importing Nuxt's build-time dependencies.
const uiDist = new URL('./', import.meta.resolve('@nuxt/ui/vite'))
let foundDefaults = false
for (const file of await readdir(new URL('shared/', uiDist))) {
    if (!file.endsWith('.mjs'))
        continue
    const source = await readFile(new URL(`shared/${file}`, uiDist), 'utf8')
    const defaults = source.match(/const defaultIcons = \{[\s\S]*?\n\};/)
    if (defaults) {
        scan(defaults[0])
        foundDefaults = true
    }
}
assert(foundDefaults, 'Could not locate Nuxt UI default icons')

const collections = Object.fromEntries(await Promise.all(['tabler', 'lucide'].map(async prefix => [
    prefix,
    JSON.parse(await readFile(require.resolve(`@iconify-json/${prefix}/icons.json`), 'utf8')),
])))
const icons = {}
for (const name of [...names].sort()) {
    const [prefix, key] = name.split(':')
    const icon = collections[prefix].icons[key]
    if (!icon?.body) {
        console.warn(`Missing icon data (renders empty): ${name}`)
        continue
    }
    icons[name] = { body: icon.body }
}
const quote = value => `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
const entries = Object.entries(icons).map(([name, icon]) => `    ${quote(name)}: { body: ${quote(icon.body)} },`)
const output = `// Generated by node scripts/generate-icons.mjs. Do not edit.\nexport const icons: Record<string, { body: string }> = {\n${entries.join('\n')}\n}\n`
const target = new URL('src/icons.ts', root)
if (process.argv.includes('--check'))
    assert.equal(await readFile(target, 'utf8'), output, 'Run node scripts/generate-icons.mjs to update icons')
else
    await writeFile(target, output)
console.log(`${Object.keys(icons).length} icons, ${Buffer.byteLength(output)} bytes: ${fileURLToPath(target)}`)
